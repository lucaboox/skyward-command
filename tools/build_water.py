"""
Build land/water masks for Skyward Command from Natural Earth data (public domain).

Outputs www/js/water.js with:
  - a fine grid around every mission zone (~3-4 km cells): where units may be placed
  - a coarse 0.5 degree world grid: where carrier strike groups may sail (pathfinding)

Usage:
  python tools/build_water.py <dir with ne_10m_land/lakes/minor_islands + ne_50m_land/lakes .geojson>
Data: https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
"""
import base64, json, math, os, subprocess, sys
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = sys.argv[1] if len(sys.argv) > 1 else '.'


def load(name):
    with open(os.path.join(DATA, name + '.geojson'), encoding='utf-8') as f:
        feats = json.load(f)['features']
    polys = []  # list of (bbox, [rings]) ; ring = [(lng,lat),...]
    for ft in feats:
        g = ft['geometry']
        if not g:
            continue
        parts = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']] if g['type'] == 'Polygon' else []
        for rings in parts:
            xs = [p[0] for p in rings[0]]; ys = [p[1] for p in rings[0]]
            polys.append(((min(xs), min(ys), max(xs), max(ys)), rings))
    return polys


def raster(bbox, w, h, land_sets, water_sets, ss=4):
    """Return a w*h list of land fractions (0..1) for a lng/lat bbox (equirectangular)."""
    lng0, lat0, lng1, lat1 = bbox
    W, H = w * ss, h * ss
    img = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(img)
    tx = lambda lng: (lng - lng0) / (lng1 - lng0) * W
    ty = lambda lat: (lat1 - lat) / (lat1 - lat0) * H

    def draw(polys, fill, hole):
        for (bx0, by0, bx1, by1), rings in polys:
            if bx1 < lng0 or bx0 > lng1 or by1 < lat0 or by0 > lat1:
                continue
            for i, ring in enumerate(rings):
                pts = [(tx(x), ty(y)) for x, y in ring]
                if len(pts) >= 3:
                    d.polygon(pts, fill=fill if i == 0 else hole)

    for s in land_sets:
        draw(s, 255, 0)
    for s in water_sets:
        draw(s, 0, 255)
    small = img.resize((w, h), Image.BOX)
    return [v / 255 for v in small.getdata()]


def pack(bits):
    out = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b:
            out[i >> 3] |= 1 << (i & 7)
    return base64.b64encode(bytes(out)).decode()


def zones():
    js = open(os.path.join(ROOT, 'www', 'js', 'data.js'), encoding='utf-8').read()
    node = "const src=require('fs').readFileSync(0,'utf8'); console.log(JSON.stringify(new Function(src+';return ZONES')()));"
    return json.loads(subprocess.run(['node', '-e', node], input=js, capture_output=True, text=True, encoding='utf-8', check=True).stdout)


def main():
    land10, lakes10, isl10 = load('ne_10m_land'), load('ne_10m_lakes'), load('ne_10m_minor_islands')
    land50, lakes50 = load('ne_50m_land'), load('ne_50m_lakes')
    out = {'zones': {}}
    N = 80
    for z in zones():
        pad = z['r'] + 40
        dlat = pad / 111.0
        dlng = pad / (111.0 * math.cos(math.radians(z['lat'])))
        bbox = (z['lng'] - dlng, z['lat'] - dlat, z['lng'] + dlng, z['lat'] + dlat)
        frac = raster(bbox, N, N, [land10, isl10], [lakes10])
        water = [f < 0.5 for f in frac]
        out['zones'][z['id']] = {'lng0': round(bbox[0], 4), 'lat0': round(bbox[1], 4), 'lng1': round(bbox[2], 4), 'lat1': round(bbox[3], 4), 'w': N, 'h': N, 'b': pack(water)}
        print(f"{z['id']:12s} water {sum(water) * 100 // len(water):3d}%")
    # world grid for ship navigation: generous to water so straits stay open
    frac = raster((-180, -90, 180, 90), 720, 360, [land50], [lakes50], ss=6)
    out['world'] = {'lng0': -180, 'lat0': -90, 'lng1': 180, 'lat1': 90, 'w': 720, 'h': 360, 'b': pack([f < 0.65 for f in frac])}
    with open(os.path.join(ROOT, 'www', 'js', 'water.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_water.py from Natural Earth (public domain). Bit = 1 means water.\n')
        f.write('const WATER_DATA = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    print('wrote www/js/water.js', os.path.getsize(os.path.join(ROOT, 'www', 'js', 'water.js')) // 1024, 'KB')


if __name__ == '__main__':
    main()
